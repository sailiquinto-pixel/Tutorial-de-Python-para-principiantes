# print() puede recibir varios valores separados por comas.
# Python los muestra separados por un espacio.
print("Python", "es", "un", "lenguaje", "muy", "versátil")

# Con números, print() puede mostrar el resultado de una operación.
print(2 + 3)

# Cuidado con la diferencia: entre comillas es TEXTO, no una operación.
print("2 + 3")

# Una línea vacía se logra con print() sin argumentos.
print()
print("Línea después de una línea vacía")

